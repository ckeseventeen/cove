import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import ts from 'typescript';
const output = ts.transpileModule(readFileSync(new URL('../src/lib/playback.ts', import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const mod = await import(`data:text/javascript;base64,${Buffer.from(output).toString('base64')}`);
const {nextQueueIndex,shuffleUpcoming,unmuteVolume} = mod;
test('repeat-one affects EOF, not the Next button',()=>{assert.equal(nextQueueIndex(1,3,'one',true),1);assert.equal(nextQueueIndex(1,3,'one'),2);});
test('queue end stops without repeat and wraps only with repeat-all',()=>{assert.equal(nextQueueIndex(2,3,'off',true),null);assert.equal(nextQueueIndex(2,3,'all',true),0);});
test('a removed or unknown track never jumps to first song',()=>assert.equal(nextQueueIndex(-1,3,'all'),null));
test('shuffle preserves playback history and has no duplicates or lost songs',()=>{const q=['a','b','c','d','e'];const result=shuffleUpcoming(q,1,()=>0);assert.deepEqual(result.slice(0,2),['a','b']);assert.deepEqual([...result].sort(),q);assert.deepEqual(q,['a','b','c','d','e']);assert.notDeepEqual(result,q);});
test('single-track and empty queues are stable',()=>{assert.deepEqual(shuffleUpcoming(['a'],0),['a']);assert.deepEqual(shuffleUpcoming([],-1),[]);assert.equal(nextQueueIndex(0,0,'all'),null);});
test('unmuting after a stop restores the level before mute, not 100',()=>{let previous=25;previous=unmuteVolume(previous,{fileId:'song',volume:0});previous=unmuteVolume(previous,{fileId:null,volume:100});assert.equal(previous,25);assert.equal(unmuteVolume(previous,{fileId:'next',volume:40}),40);});
test('track labels read as names, not codes',()=>{
  const {trackLabel}=mod;
  assert.equal(trackLabel({id:1,title:'',language:'chi'},'字幕'),'中文');
  assert.equal(trackLabel({id:2,title:'简体中文',language:'chi'},'字幕'),'简体中文');
  assert.equal(trackLabel({id:3,title:'Commentary',language:'eng'},'音轨'),'Commentary · 英语');
  assert.equal(trackLabel({id:4,title:'未命名轨道',language:''},'音轨'),'音轨 4');
  assert.equal(trackLabel({id:5,title:'',language:'zh-Hant'},'字幕'),'中文');
});
test('speed steps up and down through the list and stops at its ends', () => {
  const { stepSpeed, formatSpeed } = mod;
  assert.equal(stepSpeed(1, 1), 1.25);
  assert.equal(stepSpeed(1.5, -1), 1.25);
  assert.equal(stepSpeed(1.1, 1), 1.25);
  assert.equal(stepSpeed(3, 1), 3);
  assert.equal(stepSpeed(0.5, -1), 0.5);
  assert.deepEqual([1, 1.5, 1.25, 2].map(formatSpeed), ['1×', '1.5×', '1.25×', '2×']);
});
